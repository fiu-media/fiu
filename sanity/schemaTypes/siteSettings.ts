import { defineArrayMember, defineField, defineType } from "sanity";
import { imageArrayMember, imageWithAlt, languageField } from "./fields";

export const siteSettings = defineType({
  name: "siteSettings",
  title: "Site settings",
  type: "document",
  groups: [
    { name: "home", title: "Home", default: true },
    { name: "about", title: "About" },
    { name: "pages", title: "Page text" },
    { name: "contact", title: "Contact" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    languageField,
    defineField({
      name: "slogan",
      title: "Slogan",
      type: "string",
      group: "home",
      description: "The brand line. Keep it in Irish in every language.",
    }),
    defineField({
      name: "sloganGloss",
      title: "Slogan translation",
      type: "string",
      group: "home",
      description: "Optional, in this document's language. Leave empty for Irish.",
    }),
    defineField({
      name: "homeStills",
      title: "Home stills",
      type: "array",
      group: "home",
      description: "3–10 images that rotate behind the logo on the home page.",
      validation: (rule) => rule.min(3).max(10),
      of: [
        imageArrayMember([
          defineField({
            name: "lightTint",
            title: "Glass tint",
            type: "string",
            description:
              "Optional hex colour (e.g. #a0957b) the glass logo takes from this still. Leave empty to sample the image.",
            validation: (rule) => rule.regex(/^#[0-9a-fA-F]{6}$/, { name: "hex colour" }).warning(),
          }),
          defineField({
            name: "project",
            title: "Linked project",
            type: "reference",
            to: [{ type: "project" }],
          }),
        ]),
      ],
    }),
    defineField({ name: "manifesto", type: "array", group: "about", of: [defineArrayMember({ type: "block" })] }),
    imageWithAlt("aboutStill", "About still"),
    ...(
      [
        ["about", "About"],
        ["work", "Our Work"],
        ["talent", "Talent"],
        ["rentals", "Rentals"],
        ["contact", "Contact"],
      ] as const
    ).map(([page, label]) =>
      defineField({
        name: `${page}Tagline`,
        title: `${label}: Fiú line`,
        type: "string",
        group: "pages",
        description: `A playful line shown under the ${label} title. Leave empty to hide it.`,
      }),
    ),
    defineField({
      name: "rentalsIntro",
      title: "Rentals intro",
      type: "text",
      rows: 3,
      group: "pages",
      description: "The line under the Rentals title.",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "quoteIntro",
      title: "Request a quote intro",
      type: "text",
      rows: 3,
      group: "pages",
      description: "The line under the Request a quote title.",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "contactIntro",
      title: "Contact intro",
      type: "text",
      rows: 3,
      group: "pages",
      description: "The line under the Contact title.",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "workIntro",
      title: "Our Work intro",
      type: "text",
      rows: 3,
      group: "pages",
      description: "The line under the Our Work title. Leave empty to show just the title.",
    }),
    defineField({
      name: "talentIntro",
      title: "Talent intro",
      type: "text",
      rows: 3,
      group: "pages",
      description: "The line under the Talent title. Leave empty to show just the title.",
    }),
    defineField({ name: "instagram", title: "Instagram URL", type: "url", group: "contact" }),
    defineField({
      name: "contactEmail",
      title: "Contact email",
      type: "string",
      group: "contact",
      validation: (rule) => rule.email(),
    }),
    defineField({
      name: "quoteRecipient",
      title: "Quote request recipient",
      type: "string",
      group: "contact",
      description: "Where new rental quote requests are emailed.",
      validation: (rule) => rule.email(),
    }),
    defineField({ name: "seoTitle", title: "Default title", type: "string", group: "seo" }),
    defineField({ name: "seoDescription", title: "Default description", type: "text", rows: 3, group: "seo" }),
    defineField({ name: "seoImage", title: "Default share image", type: "image", group: "seo" }),
  ],
  preview: { prepare: () => ({ title: "Site settings" }) },
});
